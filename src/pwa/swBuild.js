/**
 * swBuild
 * Path: src/pwa/swBuild.js
 *
 * Build-time only (Node). vite.config.js uses konvaPwa(); the app never imports this file.
 * After `vite build` writes dist/, it works out the app shell, fills in the service worker
 * template (src/pwa/sw.js) and writes dist/sw.js.
 *
 * App shell = index.html, everything it loads (entry script, modulepreload chunks, CSS) and the
 * static imports of those chunks, the font files the CSS points to (Latin subsets and the icon
 * font only), and the root files from public/ (favicons, manifest, notices). Code-split chunks,
 * WASM and other font subsets are cached on first use instead.
 */
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

const TOKEN = 'self.__KONVA_SW__';

// Root files that don't belong in the offline shell. Only root files are added this way: assets/ is
// reached through index.html, and models/ and ort/ (self-hosted background removal) are cached by
// Transformers.js.
const ROOT_SKIP = new Set(['sw.js', 'robots.txt', 'og-image.png']);
const FONT_RE = /\.(woff2?|ttf|otf)$/i;
// Fontsource splits each weight by script. Konva's copy is English, so only Latin is precached;
// the browser fetches other subsets only if a character needs them, and the runtime cache keeps them.
const OTHER_SCRIPT_RE = /-(cyrillic|cyrillic-ext|greek|greek-ext|vietnamese|devanagari|hebrew|arabic|thai)-/i;

const STATIC_IMPORT_RE = /(?:\bfrom|\bimport)\s*["']([^"']+\.m?js)["']/g;
const CSS_URL_RE = /url\(\s*(['"]?)([^'")]+)\1\s*\)/g;
const HTML_REF_RE = /<(?:script|link)\b[^>]*?\s(?:src|href)=["']([^"']+)["']/gi;

function listFiles(dir) {
  const out = [];
  (function walk(d) {
    for (const entry of fs.readdirSync(d, { withFileTypes: true })) {
      const p = path.join(d, entry.name);
      if (entry.isDirectory()) walk(p);
      else out.push(path.relative(dir, p).split(path.sep).join('/'));
    }
  })(dir);
  return out.sort();
}

// Turns a URL found in HTML, CSS or JS into a dist-relative path, or null for external ones.
function toDistPath(ref, fromFile, base) {
  if (/^(?:[a-z]+:)?\/\//i.test(ref) || /^(?:data|blob|mailto):/i.test(ref) || ref.startsWith('#')) return null;
  const clean = decodeURI(ref.split(/[?#]/)[0]);
  if (!clean) return null;
  if (clean.startsWith('/')) {
    const b = base.endsWith('/') ? base : `${base}/`;
    return clean.startsWith(b) ? clean.slice(b.length) : clean.slice(1);
  }
  return path.posix.normalize(path.posix.join(path.posix.dirname(fromFile), clean));
}

function wantFont(file) {
  if (!/\.woff2$/i.test(file)) return false; // .woff/.ttf fallbacks are for very old browsers
  return !OTHER_SCRIPT_RE.test(path.posix.basename(file));
}

/**
 * Pure function (no Vite needed), so it can be run against any built folder.
 * Returns { version, precache, assets, bytes } and writes `${outDir}/sw.js`.
 */
export function buildServiceWorker({ outDir, base = '/', templateFile }) {
  const files = listFiles(outDir).filter((f) => !f.endsWith('.map'));
  const exists = new Set(files);
  if (!exists.has('index.html')) throw new Error(`konva-pwa: no index.html in ${outDir}`);

  const shell = new Set(['index.html']);
  const queue = [];
  const add = (file) => {
    if (!file || !exists.has(file) || shell.has(file)) return;
    if (FONT_RE.test(file) && !wantFont(file)) return;
    shell.add(file);
    queue.push(file);
  };

  const html = fs.readFileSync(path.join(outDir, 'index.html'), 'utf8');
  for (const m of html.matchAll(HTML_REF_RE)) add(toDistPath(m[1], 'index.html', base));

  while (queue.length) {
    const file = queue.shift();
    const text = /\.(m?js|css)$/i.test(file) ? fs.readFileSync(path.join(outDir, file), 'utf8') : '';
    if (/\.m?js$/i.test(file)) {
      for (const m of text.matchAll(STATIC_IMPORT_RE)) add(toDistPath(m[1], file, base));
    } else if (/\.css$/i.test(file)) {
      for (const m of text.matchAll(CSS_URL_RE)) add(toDistPath(m[2], file, base));
    }
  }

  for (const f of files) {
    if (!f.includes('/') && !ROOT_SKIP.has(f) && f !== 'index.html') shell.add(f);
  }

  const precache = [...shell].sort();
  const hash = createHash('sha256');
  let bytes = 0;
  for (const f of precache) {
    const buf = fs.readFileSync(path.join(outDir, f));
    bytes += buf.length;
    hash.update(f).update('\0').update(buf);
  }
  const version = hash.digest('hex').slice(0, 12);
  const assets = files.filter((f) => f.startsWith('assets/'));

  const template = fs.readFileSync(templateFile, 'utf8');
  if (template.split(TOKEN).length !== 2) throw new Error(`konva-pwa: ${templateFile} must contain ${TOKEN} once`);
  const payload = JSON.stringify({ version, precache: precache.map(encodeURI), assets: assets.map(encodeURI) });
  const banner = `/* Generated by src/pwa/swBuild.js. Edit src/pwa/sw.js instead. */\n`;
  fs.writeFileSync(path.join(outDir, 'sw.js'), banner + template.replace(TOKEN, payload));

  return { version, precache, assets, bytes };
}

export function konvaPwa() {
  let config;
  return {
    name: 'konva-pwa',
    apply: 'build',
    configResolved(resolved) {
      config = resolved;
    },
    closeBundle() {
      if (!config || config.build.ssr) return;
      const outDir = path.resolve(config.root, config.build.outDir);
      if (!fs.existsSync(path.join(outDir, 'index.html'))) return; // the build failed earlier
      const result = buildServiceWorker({
        outDir,
        base: config.base,
        templateFile: path.resolve(config.root, 'src/pwa/sw.js'),
      });
      const mb = (result.bytes / 1048576).toFixed(1);
      config.logger.info(
        `konva-pwa: sw.js precaches ${result.precache.length} files (${mb} MB), version ${result.version}`
      );
    },
  };
}
